def post(client, path, files, data=None):
    payload = dict(data or {})
    for field, paths in files.items():
        payload[field] = [(open(p, "rb"), os.path.basename(p)) for p in paths]
    response = client.post(path, data=payload, content_type="multipart/form-data")
    for handles in payload.values():
        if isinstance(handles, list):
            for h, _ in handles:
                h.close()
    if response.status_code != 200:
        raise SystemExit(f"{path} failed with HTTP {response.status_code}")
    return response


def sample(name):
    return os.path.join(EXAMPLES, name)


def link(name, label=None):
    return f'<a href="/static/examples/{name}">{label or name}</a>'


def measure_compress():
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, label in (("scanned-letter.pdf", "Scanned letter (2 pages, 200 DPI)"),
                            ("photo-brochure.pdf", "Photo brochure (3 pages, large photos)"),
                            ("text-report.pdf", "Text-only report (6 pages)")):
            original = os.path.getsize(sample(name))
            cells = []
            for level in ("low", "medium", "high", "extreme"):
                out = os.path.join(tmp, f"{level}_{name}")
                qt_app.compress_pdf(sample(name), out, level=level)
                if not os.path.exists(out):
                    raise SystemExit(f"compress {level} {name} produced no output (is Ghostscript installed?)")
                size = os.path.getsize(out)
                cells.append(f"{human(size)} ({pct(size, original)})")
            rows.append((link(name, label), human(original), *cells))
    return rows


def measure_merge(client):
    names = ["text-report.pdf", "scanned-letter.pdf", "photo-brochure.pdf"]
    r = post(client, "/merge-pdf", {"pdfs": [sample(n) for n in names]})
    merged = fitz.open(stream=r.data, filetype="pdf")
    pages_in = sum(len(fitz.open(sample(n))) for n in names)
    size_in = sum(os.path.getsize(sample(n)) for n in names)
    return {"pages_in": pages_in, "pages_out": len(merged), "size_in": size_in, "size_out": len(r.data)}


def measure_split(client):
    r = post(client, "/split-pdf", {"pdf": [sample("text-report.pdf")]})
    parts = re.findall(r'/download-file/([^"]+)"', r.get_data(as_text=True))
    sizes = [os.path.getsize(os.path.join(UPLOADS, p)) for p in parts]
    return {"original": os.path.getsize(sample("text-report.pdf")), "parts": len(parts),
            "smallest": min(sizes), "largest": max(sizes), "total": sum(sizes)}


def measure_pdf_to_word(client):
    from docx import Document
    rows, ratios = [], {}
    for name, label in (("text-report.pdf", "Text-only report (6 pages, 1 table)"),
                        ("scanned-letter.pdf", "Scanned letter (2 pages)")):
        r = post(client, "/pdf-to-word", {"pdf": [sample(name)]})
        doc = Document(io.BytesIO(r.data))
        # Non-whitespace characters on both sides, so the counts are comparable.
        texts = [p.text for p in doc.paragraphs]
        texts += [c.text for t in doc.tables for row in t.rows for c in row.cells]
        chars = sum(len("".join(t.split())) for t in texts)
        with fitz.open(sample(name)) as pdf:
            pdf_chars = sum(len("".join(p.get_text().split())) for p in pdf)
        rows.append((link(name, label), f"{pdf_chars:,}", f"{chars:,}", str(len(doc.tables)),
                     str(len(doc.inline_shapes)), human(len(r.data))))
        ratios[name] = len(r.data) / os.path.getsize(sample(name))
    return rows, ratios


def measure_jpg_to_pdf(client):
    rows = []
    for name in ("landscape-photo.jpg", "portrait-photo.jpg"):
        r = post(client, "/jpg-to-pdf", {"images": [sample(name)]})
        with Image.open(sample(name)) as im:
            px = im.size
        page = fitz.open(stream=r.data, filetype="pdf")[0].rect
        rows.append((link(name), f"{px[0]} × {px[1]} px", human(os.path.getsize(sample(name))),
                     f"{page.width / 72:.1f} × {page.height / 72:.1f} in", human(len(r.data))))
    return rows


def measure_pdf_to_jpg(client):
    rows = []
    for name, label in (("text-report.pdf", "Text-only report"), ("photo-brochure.pdf", "Photo brochure")):
        r = post(client, "/pdf-to-jpg", {"pdf": [sample(name)]})
        html = r.get_data(as_text=True)
        zip_name = re.search(r'/download-file/([^"]+\.zip)"', html).group(1)
        with zipfile.ZipFile(os.path.join(UPLOADS, zip_name)) as z:
            infos = z.infolist()
            with Image.open(io.BytesIO(z.read(infos[0]))) as im:
                dims = im.size
        sizes = [i.file_size for i in infos]
        rows.append((link(name, label), str(len(infos)), f"{dims[0]} × {dims[1]} px",
                     f"{human(min(sizes))} – {human(max(sizes))}"))
    return rows


def measure_resize(client):
    rows = []
    for name, stem in (("landscape-photo.jpg", "landscape"), ("portrait-photo.jpg", "portrait")):
        # PNG for measuring (lossless edges), JPG kept as the visible example.
        png = post(client, "/resize-image", {"image": [sample(name)]},
                   {"width": "1080", "height": "1080", "format": "png"})
        jpg = post(client, "/resize-image", {"image": [sample(name)]},
                   {"width": "1080", "height": "1080", "format": "jpg", "quality": "85"})
        out_name = f"{stem}-1080x1080.jpg"
        with open(os.path.join(EXAMPLES, out_name), "wb") as f:
            f.write(jpg.data)

        with Image.open(io.BytesIO(png.data)) as out:
            out = out.convert("RGB")
            bbox = ImageChops.difference(out, Image.new("RGB", out.size, (255, 255, 255))).getbbox()
            canvas = out.size
        with Image.open(sample(name)) as im:
            src = im.size
        content = (bbox[2] - bbox[0], bbox[3] - bbox[1])
        if content[0] < canvas[0]:
            bars = f"{(canvas[0] - content[0]) // 2} px left and right"
        else:
            bars = f"{(canvas[1] - content[1]) // 2} px top and bottom"
        rows.append({"name": name, "out": out_name, "src": src, "canvas": canvas,
                     "content": content, "bars": bars})
    return rows


# ------------------------------------------------------------- publishing

def table(headers, rows):
    head = "".join(f"<th>{h}</th>" for h in headers)
    body = "\n".join("    <tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return (f'<div class="table-wrap">\n<table class="data-table">\n  <thead><tr>{head}</tr></thead>\n'
            f"  <tbody>\n{body}\n  </tbody>\n</table>\n</div>")


def write_partial(tool, body):
    os.makedirs(PARTIALS, exist_ok=True)
    stamp = (f"{{# Generated by scripts/measure_examples.py on {TODAY.isoformat()} -- "
             f"do not edit by hand; re-run the script to refresh. #}}\n")
    footer = (f'\n<p class="file-info">Measured on {TODAY:%B} {TODAY.day}, {TODAY.year} by running the tool on '
              f"the linked sample files, which you can download and try yourself. Your own results will "
              f"depend on what's inside your file.</p>\n")
    with open(os.path.join(PARTIALS, f"{tool}.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(stamp + '<h2>Real Results: What to Expect</h2>\n' + body + footer)
    print("wrote", f"templates/components/examples/{tool}.html")


def gs_version():
    cmd = "gswin64c" if os.name == "nt" else "gs"
    return subprocess.run([cmd, "--version"], capture_output=True, text=True).stdout.strip()


def publish(results):
    c = results["compress"]
    write_partial("compress_pdf", (
        "<p>We compressed three sample PDFs at every level with the same Ghostscript engine this tool runs "
        f"(Ghostscript {results['gs']}). Low only restructures the file and keeps images at full resolution, "
        "so it barely changes image-heavy PDFs; Medium and above downsample the images, which is where the "
        "big reductions come from. A file that is mostly text has very little to remove, and Low can even "
        "make it slightly larger.</p>\n"
        + table(["Sample file", "Original", "Low", "Medium", "High", "Extreme"], c)))

    m = results["merge"]
    write_partial("merge", (
        f"<p>We merged three sample PDFs — a {link('text-report.pdf', 'text report')}, a "
        f"{link('scanned-letter.pdf', 'scanned letter')} and a {link('photo-brochure.pdf', 'photo brochure')} — "
        "in that order. Merging copies pages as they are; it doesn't re-compress anything, so the result "
        "is roughly the sum of its parts.</p>\n"
        + table(["", "Pages", "Size"], [
            ("Three input files", str(m["pages_in"]), human(m["size_in"])),
            ("Merged PDF", str(m["pages_out"]), f"{human(m['size_out'])} ({pct(m['size_out'], m['size_in'])})"),
        ])))

    s = results["split"]
    write_partial("split", (
        f"<p>We split the 6-page {link('text-report.pdf', 'sample text report')} into single pages. "
        "Each page keeps its own copy of the fonts it uses, so the pages added together come to more "
        "than the original file.</p>\n"
        + table(["", "Result"], [
            ("Original", human(s["original"])),
            ("Single-page PDFs created", str(s["parts"])),
            ("Smallest / largest page", f"{human(s['smallest'])} / {human(s['largest'])}"),
            ("All pages added together", f"{human(s['total'])} ({pct(s['total'], s['original'])})"),
        ])))

    word_rows, ratios = results["pdf_to_word"]
    write_partial("pdf_to_word", (
        "<p>We converted two sample PDFs and counted what came out in the Word file (characters are "
        "counted without spaces). A PDF with real text converts to editable text, and ruled tables "
        "become Word tables. A scanned PDF contains only pictures of text, so the Word file holds those "
        "pictures and no editable text — this tool does not run OCR. The page images are also stored "
        f"less compactly in Word: our scanned sample's .docx was {ratios['scanned-letter.pdf']:.1f}× the "
        "size of the PDF.</p>\n"
        + table(["Sample file", "Characters in PDF", "Editable characters in Word", "Tables", "Images",
                 "Word file size"], word_rows)))

    write_partial("jpg_to_pdf", (
        "<p>We converted two sample photos. Each image becomes one page whose size comes from the "
        "photo's pixel dimensions, so a large photo makes a very large page — fine on screen, but "
        "scale to fit when you print. The photo is re-encoded as it's placed in the PDF, which is why "
        "each PDF came out smaller than its JPG.</p>\n"
        + table(["Sample photo", "Pixels", "JPG size", "PDF page size", "PDF size"], results["jpg_to_pdf"])))

    write_partial("pdf_to_jpg", (
        "<p>We converted two sample A4 PDFs. Every page is rendered at 144 DPI (twice the PDF's own "
        "72-points-per-inch scale) and saved as a JPG at quality 90, up to 20 pages per file.</p>\n"
        + table(["Sample file", "Pages converted", "Image size", "JPG file size per page"], results["pdf_to_jpg"])))

    examples = results["resize"]
    figures = "\n".join(
        f'<figure class="example-figure">\n  <img src="/static/examples/{e["out"]}" width="1080" height="1080" '
        f'loading="lazy" alt="{e["src"][0]} × {e["src"][1]} photo fitted into a 1080 × 1080 square with white bars">\n'
        f'  <figcaption>{link(e["name"])} ({e["src"][0]} × {e["src"][1]}) → 1080 × 1080</figcaption>\n</figure>'
        for e in examples)
    write_partial("resize_image", (
        "<p>We resized two sample photos to a 1080 × 1080 square. The tool never crops or stretches: it "
        "scales the whole photo to fit inside the square, then fills the leftover space with white "
        "bars.</p>\n"
        + table(["Sample photo", "Original", "Output", "Photo area inside output", "White bars"],
                [(link(e["name"]), f"{e['src'][0]} × {e['src'][1]}", f"{e['canvas'][0]} × {e['canvas'][1]}",
                  f"{e['content'][0]} × {e['content'][1]}", e["bars"]) for e in examples])
        + f'\n<div class="example-figures">\n{figures}\n</div>'))


def main():
    ensure_samples("--regenerate" in sys.argv[1:])
    before = set(os.listdir(UPLOADS))
    client = qt_app.app.test_client()
    try:
        results = {
            "gs": gs_version(),
            "compress": measure_compress(),
            "merge": measure_merge(client),
            "split": measure_split(client),
            "pdf_to_word": measure_pdf_to_word(client),
            "jpg_to_pdf": measure_jpg_to_pdf(client),
            "pdf_to_jpg": measure_pdf_to_jpg(client),
            "resize": measure_resize(client),
        }
    finally:
        for name in set(os.listdir(UPLOADS)) - before:
            os.remove(os.path.join(UPLOADS, name))
    publish(results)
    for name in sorted(os.listdir(EXAMPLES)):
        print(f"  static/examples/{name}: {human(os.path.getsize(os.path.join(EXAMPLES, name)))}")


if __name__ == "__main__":
    main()
