def synthetic_photo(width, height, seed):
    """A procedurally drawn landscape: sky gradient, sun, layered hills, grain."""
    rng = np.random.default_rng(seed)
    y = np.linspace(0, 1, height)[:, None]
    x = np.linspace(0, 1, width)[None, :]

    img = np.zeros((height, width, 3))
    sky_top, sky_low = np.array([70, 120, 190]), np.array([200, 220, 235])
    img[:] = sky_top + (sky_low - sky_top) * y[..., None]

    sun_x, sun_y = rng.uniform(0.2, 0.8), rng.uniform(0.15, 0.3)
    sun = np.exp(-(((x - sun_x) * width) ** 2 + ((y - sun_y) * height) ** 2) / (2 * (0.04 * width) ** 2))
    img += sun[..., None] * np.array([55, 45, 10])

    for layer, colour in enumerate(([95, 135, 85], [70, 110, 60], [60, 85, 45])):
        knots = rng.uniform(-1, 1, 12)
        ridge = np.interp(np.linspace(0, 11, width), np.arange(12), knots)
        horizon = 0.45 + 0.12 * layer + 0.06 * ridge
        mask = y > horizon[None, :]
        shade = 1 - 0.25 * (y - horizon[None, :]).clip(0, 1)
        img = np.where(mask[..., None], np.array(colour) * shade[..., None], img)

    img += rng.normal(0, 6, img.shape)  # sensor grain
    out = Image.fromarray(img.clip(0, 255).astype("uint8"))
    return out.filter(ImageFilter.GaussianBlur(0.6))


def make_text_report(path):
    doc = fitz.open()
    for page_no in range(6):
        page = doc.new_page(width=595, height=842)  # A4
        page.insert_text((60, 70), "Riverside Bakers' Co-operative — Quarterly Report",
                         fontsize=15, fontname="helv")
        page.insert_text((60, 92), f"Section {page_no + 1}", fontsize=11, fontname="helv")
        body = "\n\n".join(PARAGRAPHS[(page_no + i) % len(PARAGRAPHS)] for i in range(4))
        page.insert_textbox(fitz.Rect(60, 110, 535, 620), body, fontsize=11, fontname="helv")
        if page_no == 0:
            # A small ruled table, so PDF to Word has a table to detect.
            rows = [["Member bakeries", "9", "11"], ["Apprentices trained", "15", "24"],
                    ["Delivery days per week", "5", "3"]]
            top = 640
            for r in range(len(rows) + 2):
                page.draw_line((60, top + r * 22), (440, top + r * 22))
            for c_x in (60, 260, 350, 440):
                page.draw_line((c_x, top), (c_x, top + 4 * 22))
            for c, head in enumerate(["Measure", "Spring", "Summer"]):
                page.insert_text(((60, 260, 350)[c] + 6, top + 15), head, fontsize=10, fontname="hebo")
            for r, row in enumerate(rows, start=1):
                for c, val in enumerate(row):
                    page.insert_text(((60, 260, 350)[c] + 6, top + r * 22 + 15), val, fontsize=10, fontname="helv")
    doc.save(path, garbage=4, deflate=True)
    doc.close()


def make_scanned_letter(path, text_pdf):
    """Two 'scanned' pages: the report pages rasterised at 200 DPI with paper tone and noise."""
    rng = np.random.default_rng(7)
    src = fitz.open(text_pdf)
    out = fitz.open()
    for i in range(2):
        pix = src[i].get_pixmap(dpi=200, colorspace=fitz.csGRAY)
        arr = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width).astype(float)
        arr = arr * 0.92 + 8 + rng.normal(0, 5, arr.shape)  # paper tone + scanner noise
        img = Image.fromarray(arr.clip(0, 255).astype("uint8")).rotate(0.4, fillcolor=240)
        buf = io.BytesIO()
        img.convert("RGB").save(buf, "JPEG", quality=80)
        page = out.new_page(width=595, height=842)
        page.insert_image(page.rect, stream=buf.getvalue())
    out.save(path)
    out.close()
    src.close()


def make_photo_brochure(path):
    doc = fitz.open()
    for i in range(3):
        page = doc.new_page(width=595, height=842)
        buf = io.BytesIO()
        synthetic_photo(2400, 1600, seed=100 + i).save(buf, "JPEG", quality=90)
        page.insert_image(fitz.Rect(40, 60, 555, 403), stream=buf.getvalue())
        page.insert_textbox(fitz.Rect(40, 420, 555, 760), PARAGRAPHS[i] + "\n\n" + PARAGRAPHS[i + 3],
                            fontsize=11, fontname="helv")
    doc.save(path)
    doc.close()


def ensure_samples(regenerate):
    if regenerate and os.path.isdir(EXAMPLES):
        shutil.rmtree(EXAMPLES)
    os.makedirs(EXAMPLES, exist_ok=True)
    f = lambda name: os.path.join(EXAMPLES, name)  # noqa: E731
    if not os.path.exists(f("text-report.pdf")):
        make_text_report(f("text-report.pdf"))
    if not os.path.exists(f("scanned-letter.pdf")):
        make_scanned_letter(f("scanned-letter.pdf"), f("text-report.pdf"))
    if not os.path.exists(f("photo-brochure.pdf")):
        make_photo_brochure(f("photo-brochure.pdf"))
    if not os.path.exists(f("landscape-photo.jpg")):
        synthetic_photo(3000, 2000, seed=1).save(f("landscape-photo.jpg"), "JPEG", quality=88)
    if not os.path.exists(f("portrait-photo.jpg")):
        synthetic_photo(1200, 1800, seed=2).save(f("portrait-photo.jpg"), "JPEG", quality=88)


