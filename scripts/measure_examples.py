def human(n):
    if n >= 1024 * 1024:
        return f"{n / (1024 * 1024):.2f} MB"
    return f"{n / 1024:.1f} KB"


def pct(new, old):
    change = (new - old) / old * 100
    if round(change, 1) == 0:
        return "no change"
    sign = "+" if change > 0 else "−"
    return f"{sign}{abs(change):.1f}%" if abs(change) < 1 else f"{sign}{abs(change):.0f}%"


