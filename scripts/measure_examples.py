"""Measure the real tools on the sample files and publish the results.

Run from the repo root (Ghostscript must be installed, as for compress-pdf):

    .venv\\Scripts\\python.exe scripts\\measure_examples.py

What it does:

1. Creates the sample files in static/examples/ if they're missing. They
   are generated by this script -- original text and procedurally drawn
   "photos", no third-party content -- so they can be regenerated at any
   time (delete the folder, or pass --regenerate).
2. Runs each sample through the actual tool code: compress_pdf() from
   app.py (the same Ghostscript engine the /compress-pdf route runs in its
   background thread) and, for every other tool, the real Flask route via
   the test client.
3. Measures the outputs (file sizes, page sizes, pixel dimensions, text
   recovered) and writes one partial per tool to
   templates/components/examples/<tool>.html, which the tool pages include.

No number on those pages is typed by hand: re-run this script to refresh
them after changing a tool. Anything the tools write to uploads/ during the
run is deleted at the end. Remove Background is not measured here -- it
needs a paid remove.bg API key and has no local engine to run.
"""

